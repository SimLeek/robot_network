_FONT: Optional[np.ndarray] = None


def _font() -> np.ndarray:
    global _FONT
    if _FONT is None:
        _FONT = _build_minimal_font()
    return _FONT


def render_text(text: str,
                color: Tuple[int, int, int] = (220, 220, 220),
                bg: Optional[Tuple[int, int, int]] = None,
                scale: int = 1) -> np.ndarray:
    """
    Render *text* (single line) as a BGRA numpy image.
    scale=1 -> 8 px per char; scale=2 -> 16 px, etc.
    """
    f = _font()
    ch = 8 * scale
    cw = 8 * scale
    w = cw * max(len(text), 1)
    img = np.zeros((ch, w, 4), dtype=np.uint8)

    if bg is not None:
        # RGB tuple -> BGRA channels
        img[:, :, 0] = bg[2]   # B
        img[:, :, 1] = bg[1]   # G
        img[:, :, 2] = bg[0]   # R
        img[:, :, 3] = 255

    # Pre-compute BGRA for text pixels (RGB input -> BGRA)
    text_bgra = np.array([color[2], color[1], color[0], 255], dtype=np.uint8)

    for i, char in enumerate(text):
        code = ord(char) if ord(char) < 256 else ord('?')
        glyph = f[code]                     # (8, 8)
        if scale > 1:
            glyph = glyph.repeat(scale, axis=0).repeat(scale, axis=1)

        x = i * cw
        mask = glyph > 0
        # Apply to the sub-rectangle (broadcasts the 4 values)
        img[:, x:x + cw][mask] = text_bgra

    return img


def render_lines(lines: List[str],
                 width: int,
                 color: Tuple[int, int, int] = (220, 220, 220),
                 bg: Optional[Tuple[int, int, int]] = None,
                 scale: int = 1,
                 line_spacing: int = 1) -> np.ndarray:
    """
    Render a list of strings into a (H, width, 4) BGRA image.
    Lines that exceed *width* are hard-truncated.
    """
    if not lines:
        lines = [""]

    line_h = 8 * scale
    stride = line_h + line_spacing
    total_h = line_h * len(lines) + line_spacing * max(0, len(lines) - 1)

    img = np.zeros((total_h, width, 4), dtype=np.uint8)
    if bg is not None:
        img[:, :, 0] = bg[2]
        img[:, :, 1] = bg[1]
        img[:, :, 2] = bg[0]
        img[:, :, 3] = 255

    for i, line in enumerate(lines):
        row = render_text(line, color=color, bg=bg, scale=scale)
        rw = min(row.shape[1], width)
        y0 = i * stride
        img[y0:y0 + line_h, :rw] = row[:, :rw]

    return img


def wrap_text(text: str, max_cols: int) -> List[str]:
    """Word-wrap *text* to at most *max_cols* characters per line."""
    import textwrap
    return textwrap.wrap(text, width=max_cols) or ['']


def cols_for_width(width: int, scale: int = 1) -> int:
    """Number of characters that fit in the given pixel width."""
    return width // (8 * scale)